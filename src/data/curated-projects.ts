import { Category } from "@prisma/client";
import type { CuratedAnalysis } from "@/lib/pipeline";

export type CuratedProject = {
  githubUrl: string;
  language: string;
  license: string;
  stars: number;
  forks: number;
  description: string;
  topics: string[];
  analysis: CuratedAnalysis;
};

function project(
  repo: string,
  category: Category,
  input: {
    type: string;
    language: string;
    license?: string;
    stars: number;
    forks?: number;
    description: string;
    summary: string;
    tags: string[];
    frameworks?: string[];
    models?: string[];
    useCases: string[];
    topics?: string[];
  },
): CuratedProject {
  return {
    githubUrl: `https://github.com/${repo}`,
    language: input.language,
    license: input.license ?? "MIT",
    stars: input.stars,
    forks: input.forks ?? Math.round(input.stars / 8),
    description: input.description,
    topics: input.topics ?? input.tags.map((t) => t.toLowerCase()),
    analysis: {
      projectType: input.type,
      category,
      tags: input.tags,
      frameworks: input.frameworks ?? [],
      models: input.models ?? [],
      useCases: input.useCases,
      summary: input.summary,
      inScope: true,
    },
  };
}

